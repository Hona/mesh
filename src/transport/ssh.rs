//! Everything SSH: the mesh client config + known_hosts, the authorized-keys
//! block, and finding the keys file the local sshd uses.

use crate::host::{paths, process};
use crate::model::Device;
use std::collections::BTreeMap;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

const BEGIN: &str = "# >>> opencode-mesh (managed, do not edit) >>>";
const END: &str = "# <<< opencode-mesh <<<";

/// Regenerate `<state>/ssh_config` and `<state>/known_hosts`; returns the ones that changed.
/// `addrs`: device name -> current address. Without one, HostName falls back to the device's host name.
pub(crate) fn write_client_files(
    devices: &[Device],
    addrs: &BTreeMap<String, String>,
) -> Result<Vec<&'static str>, String> {
    let dir = paths::state_dir();
    let mut changed = Vec::new();
    let files = [
        (
            "ssh config",
            dir.join("ssh_config"),
            client_config(devices, addrs, &dir),
        ),
        (
            "known_hosts",
            dir.join("known_hosts"),
            known_hosts(devices, addrs),
        ),
    ];
    for (label, path, text) in files {
        if fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
            fs::create_dir_all(&dir).map_err(|e| format!("{}: {e}", dir.display()))?;
            fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))?;
            changed.push(label);
        }
    }
    Ok(changed)
}

/// Path as written into ssh config: forward slashes, quoted if it has spaces.
fn ssh_path(p: &Path) -> String {
    let s = p.display().to_string().replace('\\', "/");
    if s.contains(' ') {
        format!("\"{s}\"")
    } else {
        s
    }
}

fn client_config(devices: &[Device], addrs: &BTreeMap<String, String>, dir: &Path) -> String {
    let key = ssh_path(&dir.join("id_ed25519"));
    let known = ssh_path(&dir.join("known_hosts"));
    let mut s = String::from("# generated by mesh sync, do not edit\n");
    for d in devices {
        let host = addrs.get(&d.name).unwrap_or(&d.host);
        s += &format!("\nHost {}\n  HostName {host}\n", d.name);
        if !d.user.is_empty() {
            s += &format!("  User {}\n", d.user);
        }
        s += &format!(
            "  IdentityFile {key}\n  IdentitiesOnly yes\n  UserKnownHostsFile {known}\n  \
             StrictHostKeyChecking yes\n  BatchMode yes\n  ConnectTimeout 5\n  ServerAliveInterval 15\n"
        );
    }
    s
}

fn known_hosts(devices: &[Device], addrs: &BTreeMap<String, String>) -> String {
    let mut s = String::new();
    for d in devices {
        let Some(keys) = &d.host_key else { continue };
        let mut names = vec![d.name.clone()];
        if !d.host.eq_ignore_ascii_case(&d.name) {
            names.push(d.host.to_lowercase());
        }
        names.extend(addrs.get(&d.name).cloned());
        for line in keys.lines().filter(|l| !l.trim_start().starts_with('#')) {
            let mut t = line.split_whitespace();
            if let (Some(kind), Some(key)) = (t.next(), t.next()) {
                s += &format!("{} {kind} {key}\n", names.join(","));
            }
        }
    }
    s
}

/// Rewrite the managed block in the keys file the local sshd uses for this user.
/// Ok(true) if the file changed; Err(reason) if it was skipped.
pub(crate) fn authorize(devices: &[Device]) -> Result<bool, String> {
    let path = keys_file()?;
    let keys: Vec<&str> = devices
        .iter()
        .filter_map(|d| d.key.as_deref())
        .flat_map(str::lines)
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .collect();
    let old = match fs::read_to_string(&path) {
        Ok(s) => s,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => String::new(),
        Err(e) => return Err(io_reason(&path, e)),
    };
    if keys.is_empty() && !old.contains(BEGIN) {
        return Ok(false);
    }
    let block = format!(
        "{BEGIN}\n{}{END}\n",
        keys.iter().map(|k| format!("{k}\n")).collect::<String>()
    );
    let new = with_block(&old, &block).ok_or_else(|| {
        format!(
            "{}: managed block markers are broken, fix them by hand",
            path.display()
        )
    })?;
    if new == old {
        return Ok(false);
    }
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir).map_err(|e| io_reason(dir, e))?;
    }
    // Write in place so the file keeps its ACL / permissions.
    let mut f = fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .open(&path)
        .map_err(|e| io_reason(&path, e))?;
    f.write_all(new.as_bytes())
        .map_err(|e| io_reason(&path, e))?;
    Ok(true)
}

fn io_reason(p: &Path, e: std::io::Error) -> String {
    if e.kind() == std::io::ErrorKind::PermissionDenied {
        format!(
            "{} needs admin (mesh up sets up the elevated keys task)",
            p.display()
        )
    } else {
        format!("{}: {e}", p.display())
    }
}

/// Replace the managed block, or append it. None if the markers are unbalanced.
fn with_block(old: &str, block: &str) -> Option<String> {
    let mut out = String::new();
    let mut inside = false;
    let mut placed = false;
    for line in old.split_inclusive('\n') {
        let t = line.trim_end();
        if !inside && t == BEGIN {
            inside = true;
            if !placed {
                out += block;
                placed = true;
            }
        } else if inside {
            inside = t != END;
        } else {
            out += line;
        }
    }
    if inside {
        return None;
    }
    if !placed {
        if !out.is_empty() && !out.ends_with('\n') {
            out.push('\n');
        }
        out += block;
    }
    Some(out)
}

/// Windows writes this sshd_config on first start; same answer before that.
const WINDOWS_DEFAULT_CONFIG: &str = "AuthorizedKeysFile .ssh/authorized_keys\n\
    Match Group administrators\n\
    AuthorizedKeysFile __PROGRAMDATA__/ssh/administrators_authorized_keys\n";

/// The authorized-keys file the local SSH server uses for this user.
fn keys_file() -> Result<PathBuf, String> {
    let home = paths::home();
    let program_data =
        paths::env_dir("ProgramData").unwrap_or_else(|| PathBuf::from(r"C:\ProgramData"));
    let (installed, config) = if cfg!(windows) {
        let sys = paths::env_dir("SystemRoot").unwrap_or_else(|| PathBuf::from(r"C:\Windows"));
        (
            sys.join(r"System32\OpenSSH\sshd.exe").is_file(),
            program_data.join(r"ssh\sshd_config"),
        )
    } else {
        let found = ["/usr/sbin/sshd", "/usr/bin/sshd", "/usr/local/sbin/sshd"]
            .iter()
            .any(|p| Path::new(p).is_file());
        (found, PathBuf::from("/etc/ssh/sshd_config"))
    };
    if !installed {
        return Err("no SSH server installed (mesh up sets one up)".into());
    }
    let text = fs::read_to_string(&config).unwrap_or_else(|_| {
        if cfg!(windows) {
            WINDOWS_DEFAULT_CONFIG.into()
        } else {
            String::new()
        }
    });
    let value = configured(&text, cfg!(windows) && process::is_admin());
    let first = value
        .as_deref()
        .and_then(|v| v.split_whitespace().next())
        .unwrap_or(".ssh/authorized_keys");
    if first.eq_ignore_ascii_case("none") {
        return Err("sshd_config sets AuthorizedKeysFile none".into());
    }
    let user = std::env::var(if cfg!(windows) { "USERNAME" } else { "USER" }).unwrap_or_default();
    let expanded = first
        .replace("__PROGRAMDATA__", &program_data.display().to_string())
        .replace("%h", &home.display().to_string())
        .replace("%u", &user)
        .replace("%%", "%");
    let p = PathBuf::from(expanded);
    Ok(if p.is_relative() { home.join(p) } else { p })
}

/// AuthorizedKeysFile from sshd_config: the global value, overridden by
/// `Match Group administrators` (or `Match all`) for admins.
fn configured(text: &str, admin: bool) -> Option<String> {
    let (mut global, mut matched) = (None, None);
    let mut block: Option<bool> = None;
    for line in text.lines().map(str::trim) {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let (key, val) = line
            .split_once(|c: char| c.is_whitespace() || c == '=')
            .unwrap_or((line, ""));
        let val = val
            .trim_start_matches(|c: char| c.is_whitespace() || c == '=')
            .trim();
        if key.eq_ignore_ascii_case("Match") {
            let w: Vec<&str> = val.split_whitespace().collect();
            block = Some(match w.as_slice() {
                [k] => k.eq_ignore_ascii_case("all"),
                [k, groups] if k.eq_ignore_ascii_case("group") => {
                    admin
                        && groups
                            .split(',')
                            .any(|g| g.trim_matches('"').eq_ignore_ascii_case("administrators"))
                }
                _ => false,
            });
        } else if key.eq_ignore_ascii_case("AuthorizedKeysFile") {
            match block {
                None => global = global.or(Some(val.to_string())),
                Some(true) => matched = matched.or(Some(val.to_string())),
                Some(false) => {}
            }
        }
    }
    matched.or(global)
}
